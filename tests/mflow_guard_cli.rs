#[test]
fn packing_the_refs_keeps_the_branch_and_the_guard() {
    let repo = Repo::new();
    let old = repo.commit("a");
    let tip = repo.commit("b");
    repo.install_hook("v2026.11.0");
    // The maintenance shapes the audit probed: they fold the loose ref into the packed one
    // and must not read as a deletion of the branch (audit B3).
    repo.git_ok(&["pack-refs", "--all"]);
    repo.git_ok(&["maintenance", "run", "--task=pack-refs"]);
    repo.git_ok(&["gc"]);
    assert_eq!(
        repo.rev("v2026.11.0"),
        tip,
        "the branch keeps its value through packing"
    );
    // The guard still stands once the branch is packed only: the packed-only branch is not
    // deletable and still refuses a backward move.
    let out = repo.git(&["update-ref", "-d", "refs/heads/v2026.11.0"]);
    assert!(
        !out.success,
        "the packed branch is still not deletable: {}",
        out.stderr
    );
    let out = repo.git(&["update-ref", "refs/heads/v2026.11.0", &old]);
    assert!(
        !out.success,
        "the packed branch still refuses a backward move: {}",
        out.stderr
    );
}

#[cfg(unix)] // runs the script with sh directly; git-for-windows carries sh, a bare box may not (audit N10)
#[test]
fn the_hook_leaves_the_committed_and_aborted_phases_alone() {
    let repo = Repo::new();
    let old = repo.commit("a");
    let tip = repo.commit("b");
    repo.install_hook("v2026.11.0");
    // One real backward-move line, so the phase gate is what passes the phase: on an empty
    // transaction a gate mutant would survive unnoticed (audit N1).
    let line = format!("{tip} {old} refs/heads/v2026.11.0\n");
    use std::io::Write as _;
    for phase in ["committed", "aborted"] {
        let mut child = std::process::Command::new("sh")
            .arg(".git/hooks/reference-transaction")
            .arg(phase)
            .current_dir(&repo.0)
            .stdin(std::process::Stdio::piped())
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()
            .unwrap();
        child
            .stdin
            .as_mut()
            .unwrap()
            .write_all(line.as_bytes())
            .unwrap();
        drop(child.stdin.take());
        let out = child.wait_with_output().unwrap();
        assert!(
            out.status.success(),
            "the {phase} phase is not judged: {}",
            String::from_utf8_lossy(&out.stderr)
        );
    }
}

#[test]
fn the_override_lets_it_through_and_records_one_line() {
    let repo = Repo::new();
    let old = repo.commit("a");
    let tip = repo.commit("b");
    repo.install_hook("v2026.11.0");
    let out = repo.git_env(
        OVERRIDE_ENV,
        "decision-note-1",
        &["update-ref", "refs/heads/v2026.11.0", &old],
    );
    assert!(out.success, "the override let it through: {}", out.stderr);
    let log = fs::read_to_string(repo.0.join(LOG_FILE)).unwrap();
    let lines: Vec<&str> = log.lines().collect();
    assert_eq!(lines.len(), 1, "one record line: {log:?}");
    assert!(
        log.contains("decision-note-1"),
        "the note reference is recorded: {log:?}"
    );
    // REQ-4 golden: `<utc> override <variable>=<note> <ref> <held> -> <pushed>` — the value
    // the branch held at the transaction, then the value the command pushed.
    let parts: Vec<String> = lines[0].split_whitespace().map(str::to_string).collect();
    assert_eq!(parts.len(), 7, "seven fields: {log:?}");
    assert_eq!(parts[0].len(), 20, "a UTC stamp: {log:?}");
    assert!(parts[0].ends_with('Z'), "a UTC stamp: {log:?}");
    assert_eq!(parts[1], "override", "{log:?}");
    assert_eq!(
        parts[2],
        format!("{OVERRIDE_ENV}=decision-note-1"),
        "the note rides its variable: {log:?}"
    );
    assert_eq!(parts[3], "refs/heads/v2026.11.0", "{log:?}");
    assert_eq!(parts[4], tip, "the value the branch held: {log:?}");
    assert_eq!(parts[5], "->", "{log:?}");
    assert_eq!(parts[6], old, "the value it was pushed to: {log:?}");
}

#[test]
fn an_override_value_without_a_note_shape_is_no_exception() {
    // "=1" is not a note reference and a newline could forge record lines: both read as no
    // override — the refusal stands and nothing is logged (audit N2).
    for bad in ["=1", "note\nforged"] {
        let repo = Repo::new();
        let old = repo.commit("a");
        repo.commit("b");
        repo.install_hook("v2026.11.0");
        let out = repo.git_env(
            OVERRIDE_ENV,
            bad,
            &["update-ref", "refs/heads/v2026.11.0", &old],
        );
        assert!(
            !out.success,
            "the malformed override {bad:?} is no exception: {}",
            out.stderr
        );
        assert!(
            !repo.0.join(LOG_FILE).exists(),
            "nothing is logged for {bad:?}"
        );
    }
}

