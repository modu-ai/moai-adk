//! #3004 P4-1 / P4-2: the files the generators wrote before the hook command name changed from
//! `moai-cli` to `moai` (P4-2) and the status line default follows (P4-3). The fixtures under
//! `tests/fixtures/hooks-pre-p4/` were captured by running the generators (`hooks-plan` /
//! `hooks-apply`, `claude-settings-plan` / `-apply`) of the commit before P4-2 in a temporary
//! project with a temporary HOME. They are the legacy start state of the rewrite tests. Since
//! P4-2 this test rebuilds each file with the LEGACY generator (the current generator called
//! with the old binary name, `hooks::LEGACY_BINARY`) and compares bytes, so it guards both the
//! fixtures and the legacy set the rewrite recognises: a change that moves either by accident
//! fails here. It also checks that no fixture equals what is generated now. The receipts carry
//! no timestamp and no path, so nothing is normalized.
#![cfg(unix)]

use moai_cli::{claude, hooks, status_line};
use serde_json::{json, Map, Value};
use std::{fs, path::Path};
use tempfile::TempDir;

const FIXTURES: &str = concat!(env!("CARGO_MANIFEST_DIR"), "/tests/fixtures/hooks-pre-p4");
const LANE: Option<(&str, &str)> = Some(("agent-1", "o/r"));

fn fixture(name: &str) -> Vec<u8> {
    fs::read(Path::new(FIXTURES).join(name)).unwrap()
}

fn fixture_json(name: &str) -> Value {
    serde_json::from_slice(&fixture(name)).unwrap()
}

/// Compares generated bytes with `FIXTURES/<name>` byte for byte.
fn same(got: &[u8], name: &str) {
    let want = fixture(name);
    assert_eq!(
        String::from_utf8_lossy(got),
        String::from_utf8_lossy(&want),
        "the legacy generator no longer matches tests/fixtures/hooks-pre-p4/{name}"
    );
    assert_eq!(got, want.as_slice(), "differs from {name} in bytes");
}

fn pretty(v: &Value) -> Vec<u8> {
    let mut b = serde_json::to_vec_pretty(v).unwrap();
    b.push(b'\n');
    b
}

/// The receipt of a Codex or OMP install of `file` with the legacy set.
fn file_receipt_matches(receipt: &str, hooks_path: &str, file: &[u8], list: Value) {
    let r = fixture_json(receipt);
    assert_eq!(r["schema_version"], json!(1));
    assert_eq!(r["hooks_path"], json!(hooks_path));
    assert_eq!(r["sha256"], json!(moai_cli::digest(file)), "{receipt}");
    assert_eq!(r["hooks"], list, "{receipt}");
    assert!(r.get("pending_sha256").is_none(), "{receipt}");
}

/// No fixture is the current generator's output, and every command in it names `moai-cli`.
fn is_legacy(name: &str, current: &[u8]) {
    let got = fixture(name);
    assert_ne!(got, current, "{name} equals the current generator's bytes");
    assert!(String::from_utf8_lossy(&got).contains("moai-cli"), "{name}");
}

#[test]
fn claude_project_settings_and_receipt_match_the_legacy_generator() {
    let legacy = hooks::legacy_hooks("claude", None).unwrap();
    let settings = pretty(&json!({"hooks": legacy}));
    same(&settings, "claude.settings.json");
    let r = fixture_json("claude.receipt.json");
    assert_eq!(r["schema_version"], json!(1));
    assert_eq!(r["settings_path"], json!(".claude/settings.json"));
    assert_eq!(r["owned"], json!({"hooks": legacy}));
    assert_eq!(r["settings_sha256"], json!(moai_cli::digest(&settings)));
    assert!(r.get("pending").is_none());
    let current = pretty(&json!({"hooks": hooks::current_hooks("claude", None).unwrap()}));
    is_legacy("claude.settings.json", &current);
}

#[test]
fn codex_hooks_file_and_receipt_match_the_legacy_generator() {
    let file = hooks::legacy_codex_file(None).unwrap();
    same(&file, "codex.hooks.json");
    file_receipt_matches(
        "codex.receipt.json",
        ".codex/hooks.json",
        &file,
        hooks::hook_list_of(hooks::LEGACY_BINARY, "codex", None),
    );
    let doc = fixture_json("codex.hooks.json");
    assert_eq!(
        doc["hooks"],
        json!(hooks::legacy_hooks("codex", None).unwrap())
    );
    assert!(doc["description"]
        .as_str()
        .unwrap()
        .contains("generated by moai-cli hooks-apply"));
    // What the current generator writes into a fresh project differs from the fixture.
    let dir = TempDir::new().unwrap();
    fs::create_dir_all(dir.path().join(".moai-cli")).unwrap();
    let plan = hooks::plan(dir.path(), "codex", None).unwrap();
    hooks::apply(
        dir.path(),
        "codex",
        None,
        plan["plan_digest"].as_str().unwrap(),
        "fixture",
    )
    .unwrap();
    let current = fs::read(dir.path().join(".codex/hooks.json")).unwrap();
    is_legacy("codex.hooks.json", &current);
}

#[test]
fn omp_extension_and_receipt_match_the_legacy_generator() {
    let module = hooks::omp_module(hooks::LEGACY_BINARY);
    same(module.as_bytes(), "omp.moai-hooks.ts");
    file_receipt_matches(
        "omp.receipt.json",
        ".omp/extensions/moai-hooks.ts",
        module.as_bytes(),
        hooks::hook_list_of(hooks::LEGACY_BINARY, "omp", None),
    );
    is_legacy(
        "omp.moai-hooks.ts",
        hooks::omp_module(hooks::HOOK_BINARY).as_bytes(),
    );
}

#[test]
fn the_codex_lane_stop_group_matches_the_legacy_generator() {
    let file = hooks::legacy_codex_file(LANE).unwrap();
    same(&file, "codex-lane.hooks.json");
    file_receipt_matches(
        "codex-lane.receipt.json",
        ".codex/hooks.json",
        &file,
        hooks::hook_list_of(hooks::LEGACY_BINARY, "codex", LANE),
    );
    let r = fixture_json("codex-lane.receipt.json");
    assert_eq!(r["lane_loop"], json!({"lane": "agent-1", "repo": "o/r"}));
    let stop = &fixture_json("codex-lane.hooks.json")["hooks"]["Stop"];
    assert_eq!(
        stop[0]["hooks"][0]["command"],
        json!("moai-cli lane-stop-hook --lane agent-1 --repo o/r")
    );
}

/// A project with the state folder, temporary.
fn project() -> (TempDir, std::path::PathBuf) {
    let dir = TempDir::new().unwrap();
    let root = fs::canonicalize(dir.path()).unwrap();
    let project = root.join("project");
    fs::create_dir_all(project.join(".moai-cli")).unwrap();
    (dir, project)
}

/// Compares `project/<generated>` with `FIXTURES/<fixture>` byte for byte.
fn same_file(project: &Path, generated: &str, fixture_name: &str) {
    same(&fs::read(project.join(generated)).unwrap(), fixture_name);
}

#[test]
fn an_owned_status_line_matches_the_pre_p4_bytes() {
    let (_d, project) = project();
    let mut input = Map::new();
    // The legacy status line generator (#3004 P4-3): the current generator called with the old
    // binary name, equal to the captured pre-P4 bytes.
    input.insert("statusLine".into(), status_line::legacy());
    let desired = claude::user_settings_desired(&project, &input).unwrap();
    let plan = claude::settings_plan(&project, &desired).unwrap();
    let digest = plan["plan_digest"].as_str().unwrap().to_string();
    let applied: Value = claude::settings_apply(&project, &desired, &digest, "fixture").unwrap();
    assert!(applied.is_object(), "{applied}");
    same_file(
        &project,
        ".claude/settings.json",
        "statusline.settings.json",
    );
    same_file(
        &project,
        ".moai-cli/manifests/claude-settings.json",
        "statusline.receipt.json",
    );
}

/// #3004 P4-3: the status line the generator writes now is `moai statusline`; it is not the
/// captured bytes, and the captured bytes still hold the old command, so the fixtures keep
/// pinning what the earlier releases wrote.
#[test]
fn the_current_status_line_differs_from_the_pre_p4_bytes() {
    assert_eq!(
        status_line::legacy(),
        json!({"type": "command", "command": "moai-cli statusline"})
    );
    assert_eq!(
        status_line::current(),
        json!({"type": "command", "command": "moai statusline"})
    );
    let (_d, project) = project();
    let mut input = Map::new();
    input.insert("statusLine".into(), status_line::current());
    let desired = claude::user_settings_desired(&project, &input).unwrap();
    let plan = claude::settings_plan(&project, &desired).unwrap();
    let digest = plan["plan_digest"].as_str().unwrap().to_string();
    claude::settings_apply(&project, &desired, &digest, "fixture").unwrap();
    for (generated, name) in [
        (".claude/settings.json", "statusline.settings.json"),
        (
            ".moai-cli/manifests/claude-settings.json",
            "statusline.receipt.json",
        ),
    ] {
        is_legacy(name, &fs::read(project.join(generated)).unwrap());
    }
}
