//! Collects the internal operations under `src/ops/` into one generated registry (#2617,
//! #2388 AC-2). Each `src/ops/<word>.rs` (the file name is the subcommand with `-` as `_`)
//! declares `pub struct Args` (clap `Args`), `pub const OPERATION: &str` and
//! `pub fn run(args: Args) -> Result<serde_json::Value, String>`. A new operation is one new
//! file there: no shared line in `src/main.rs` or a shared document list changes, so two
//! branches that each add an operation merge without a conflict.

use std::{env, fs, path::Path};

fn camel(word: &str) -> String {
    word.split('_')
        .map(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .map(|c| c.to_ascii_uppercase().to_string() + chars.as_str())
                .unwrap_or_default()
        })
        .collect()
}

/// The `///` lines right above `pub struct Args`, so the subcommand keeps its help text.
fn args_doc(text: &str) -> Vec<String> {
    let lines: Vec<&str> = text.lines().collect();
    let Some(at) = lines
        .iter()
        .position(|l| l.trim_start().starts_with("pub struct Args"))
    else {
        return Vec::new();
    };
    let mut doc = Vec::new();
    for line in lines[..at].iter().rev() {
        let t = line.trim_start();
        if let Some(rest) = t.strip_prefix("///") {
            doc.push(rest.strip_prefix(' ').unwrap_or(rest).to_string());
        } else if t.starts_with("#[") {
            continue;
        } else {
            break;
        }
    }
    doc.reverse();
    doc
}

fn main() {
    let root = env::var("CARGO_MANIFEST_DIR").expect("manifest dir");
    let dir = Path::new(&root).join("src/ops");
    println!("cargo:rerun-if-changed=src/ops");
    let mut words: Vec<String> = fs::read_dir(&dir)
        .expect("src/ops is readable")
        .map(|e| {
            e.expect("src/ops entry")
                .file_name()
                .to_string_lossy()
                .into_owned()
        })
        .filter_map(|name| name.strip_suffix(".rs").map(str::to_string))
        .filter(|word| word != "mod")
        .collect();
    words.sort();
    for word in &words {
        assert!(
            !word.is_empty()
                && word
                    .bytes()
                    .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_')
                && !word.starts_with('_')
                && !word.ends_with('_')
                && !word.contains("__"),
            "src/ops/{word}.rs: an operation file name is lowercase words joined by `_`"
        );
        println!("cargo:rerun-if-changed=src/ops/{word}.rs");
    }
    let mut out =
        String::from("// Generated by build.rs from src/ops/*.rs (#2617). Do not edit.\n\n");
    for word in &words {
        let path = dir.join(format!("{word}.rs"));
        out.push_str(&format!(
            "#[path = {:?}]\npub mod {word};\n",
            path.display().to_string()
        ));
    }
    out.push_str("\n/// The operations collected from `src/ops/`, in file-name order.\n");
    out.push_str("#[derive(clap::Subcommand)]\npub enum Ops {\n");
    for word in &words {
        let text = fs::read_to_string(dir.join(format!("{word}.rs"))).expect("operation file");
        for line in args_doc(&text) {
            out.push_str(&format!("    #[doc = {line:?}]\n"));
        }
        out.push_str(&format!("    {}({word}::Args),\n", camel(word)));
    }
    out.push_str("}\n\nimpl Ops {\n    /// The envelope operation name.\n");
    out.push_str("    pub fn operation(&self) -> &'static str {\n        match self {\n");
    for word in &words {
        out.push_str(&format!(
            "            Ops::{}(_) => {word}::OPERATION,\n",
            camel(word)
        ));
    }
    out.push_str("        }\n    }\n\n    /// Runs the operation; `main` wraps the result in the envelope.\n");
    out.push_str(
        "    pub fn run(self) -> Result<serde_json::Value, String> {\n        match self {\n",
    );
    for word in &words {
        out.push_str(&format!(
            "            Ops::{}(args) => {word}::run(args),\n",
            camel(word)
        ));
    }
    out.push_str("        }\n    }\n}\n");
    let target = Path::new(&env::var("OUT_DIR").expect("out dir")).join("ops_registry.rs");
    fs::write(target, out).expect("write the operation registry");
}
