//! The M-Flow forward-only guard for the local integration branch (SPEC-20261121-mflow-forward-guard):
//! the reference-transaction hook script a project installs, and the command words the tool guard
//! refuses. The integration branch and its name come from the project profile's `work_flow`.
//!
//! The generated script is self-contained: the branch, the override variable and the log path are
//! baked in at install time, so the guard runs where the tool is not on PATH. `prepared` is the
//! only transaction phase it judges — refusing there aborts the transaction — and
//! `git merge-base --is-ancestor` decides whether the branch moves forward. An update is an
//! exception only when the override variable names a decision note, and every exception appends
//! one record line to the guard log.

/// The variable whose value names the decision note of an exception.
pub const OVERRIDE_ENV: &str = "MOAI_MFLOW_FORWARD_OVERRIDE";

/// The project-relative guard log the exceptions append to.
pub const LOG_FILE: &str = ".moai/mflow-forward.log";

/// The reference-transaction hook script for one integration branch. The branch, the override
/// variable and the log path are baked in; the script reads nothing else at run time.
///
/// The old value comes from `git rev-parse --verify` on the branch, not from the transaction
/// line: this git reports the line's old value as zeros for an `update-ref`, which would read
/// as a creation. The branch still holds its old value while the transaction is preparing or
/// prepared, the two phases the guard judges — refusing there aborts the transaction.
pub fn hook_script(branch: &str, override_env: &str, log_file: &str) -> String {
    format!(
        r#"#!/bin/sh
# Forward-only guard for refs/heads/{branch} (generated by the install step; an edit makes the
# next install plan stop for review).
state="$1"
[ "$state" = "preparing" ] || [ "$state" = "prepared" ] || exit 0
mkdir -p "$(dirname "{log_file}")" 2>/dev/null || true
ref="refs/heads/{branch}"
zero=0000000000000000000000000000000000000000
while read -r old new name; do
    [ "$name" = "$ref" ] || continue
    if [ "$new" = "$zero" ]; then
        if [ -n "${{{override_env}}}" ]; then
            old_now=$(git rev-parse --verify "$ref" 2>/dev/null || echo "$zero")
            [ "$state" = "prepared" ] && printf '%s override %s=%s %s %s -> %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "{override_env}" "${{{override_env}}}" "$ref" "$old_now" "$new" >> "{log_file}"
            continue
        fi
        echo "m-flow guard: $ref may not be deleted; a revert commit on top is the forward-only way" >&2
        exit 1
    fi
    old_now=$(git rev-parse --verify "$ref" 2>/dev/null || echo "$zero")
    [ "$old_now" = "$zero" ] && continue
    if git merge-base --is-ancestor "$old_now" "$new" 2>/dev/null; then
        continue
    fi
    if [ -n "${{{override_env}}}" ]; then
        [ "$state" = "prepared" ] && printf '%s override %s=%s %s %s -> %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "{override_env}" "${{{override_env}}}" "$ref" "$old_now" "$new" >> "{log_file}"
        continue
    fi
    echo "m-flow guard: $ref may only move forward ($old_now -> $new); a revert commit on top is the forward-only way" >&2
    exit 1
done
exit 0
"#
    )
}

/// The command words the tool guard refuses before they run: `Some` with the reason when the
/// command aims a forward-breaking git command at the integration branch, `None` when it does
/// not name the branch or names no refused command.
pub fn guard_rule(command: &str, integration_branch: &str) -> Option<String> {
    let words: Vec<&str> = command.split_whitespace().collect();
    if words.first() != Some(&"git") {
        return None;
    }
    let branch_ref = format!("refs/heads/{integration_branch}");
    let aims_at_branch = command.contains(&format!(" {integration_branch}"))
        || command.ends_with(integration_branch)
        || command.contains(&branch_ref);
    if !aims_at_branch {
        return None;
    }
    let sub = words.get(1).copied();
    let force = |names: &[&str]| words.iter().any(|w| names.contains(w));
    if sub == Some("reset") && force(&["--hard", "--keep"]) {
        return Some(format!(
            "m-flow guard: git reset on the integration branch {integration_branch} moves it \
             backwards; add a revert commit on top"
        ));
    }
    if sub == Some("push") && force(&["--force", "--force-with-lease", "-f"]) {
        return Some(format!(
            "m-flow guard: git push --force to the integration branch {integration_branch} can \
             move it backwards; push a forward commit"
        ));
    }
    if sub == Some("branch") && force(&["-f", "--force", "-D"]) {
        return Some(format!(
            "m-flow guard: git branch -f/-D on the integration branch {integration_branch} is \
             refused; use git branch -d once it is merged"
        ));
    }
    None
}
