//! The M-Flow forward-only guard for the local integration branch (SPEC-20261121-mflow-forward-guard):
//! the reference-transaction hook script a project installs, and the command words the tool guard
//! refuses. The integration branch and its name come from the project profile's `work_flow`.
//!
//! The generated script is self-contained: the branch, the override variable and the log path are
//! baked in at install time, so the guard runs where the tool is not on PATH. Only the
//! `preparing` and `prepared` transaction phases are judged — refusing there aborts the
//! transaction — and `git merge-base --is-ancestor` decides whether the branch moves forward.
//! An update is an exception only when the override variable names a decision note, and every
//! exception appends one record line to the guard log.

use crate::claim_verify::GitSub;
use crate::ledger::LedgerError;
use std::path::Path;

/// The variable whose value names the decision note of an exception.
pub const OVERRIDE_ENV: &str = "MOAI_MFLOW_FORWARD_OVERRIDE";

/// The guard log the exceptions append to, read relative to the folder the hook runs in. The
/// install step bakes the primary checkout's state root — the absolute path of the primary's
/// `.moai` folder — so linked worktrees share one log; a relative path gives each worktree its
/// own log (audit N3).
pub const LOG_FILE: &str = ".moai/mflow-forward.log";

/// The reference-transaction hook script for one integration branch. The branch, the override
/// variable and the log path are baked in, shell-quoted; the script reads nothing else at run
/// time. The log path must be the primary checkout's state root (see `LOG_FILE`), so the
/// linked worktrees share one log.
///
/// The old value comes from `git rev-parse --verify` on the branch, not from the transaction
/// line: this git reports the line's old value as zeros for an `update-ref`, which would read
/// as a creation. The branch still holds its old value while the transaction is preparing or
/// prepared, the two phases the guard judges — refusing there aborts the transaction.
pub fn hook_script(branch: &str, override_env: &str, log_file: &str) -> String {
    let branch = sh_word(branch);
    let override_env = sh_word(override_env);
    let log_file = sh_word(log_file);
    format!(
        r#"#!/bin/sh
# Forward-only guard for refs/heads/{branch} (generated by the install step; an edit makes the
# next install plan stop for review).
state="$1"
[ "$state" = "preparing" ] || [ "$state" = "prepared" ] || exit 0
BRANCH={branch}
LOG={log_file}
OVERRIDE_NAME={override_env}
ref="refs/heads/$BRANCH"
zero=0000000000000000000000000000000000000000
# The override value must look like a decision-note reference: one line, no control
# characters, no leading '='. Anything else is no exception, and nothing is logged.
value=$(printenv "$OVERRIDE_NAME" 2>/dev/null || echo "")
case "$value" in
    ""|*[[:cntrl:]]*|'='*) value="" ;;
esac
while read -r old new name; do
    [ "$name" = "$ref" ] || continue
    if [ "$new" = "$zero" ]; then
        # pack-refs and maintenance remove the loose ref while the packed one keeps the
        # value: the parent's git subcommand names the task (audit B3). The subcommand is
        # the first word after git that is not an option, and the options that take a
        # separate value word (-c gc.auto=0 and friends) are read past — a substring match
        # on the whole command line would let any guarded call through.
        set -f
        parent=$(ps -o command= -p "$PPID" 2>/dev/null || echo "")
        sub=""
        seen_git=""
        skip_value=""
        for word in $parent; do
            if [ -z "$seen_git" ]; then
                case "$word" in
                    git|*/git) seen_git=1 ;;
                esac
                continue
            fi
            if [ -n "$skip_value" ]; then
                skip_value=""
                continue
            fi
            case "$word" in
                -c|-C|--git-dir|--work-tree|--namespace|--super-prefix|--attr-source)
                    skip_value=1 ;;
                -*) ;;
                *) sub="$word" ; break ;;
            esac
        done
        case "$sub" in
            pack-refs|gc|maintenance) continue ;;
        esac
        if [ -n "$value" ]; then
            old_now=$(git rev-parse --verify "$ref" 2>/dev/null || echo "$zero")
            [ "$state" = "prepared" ] && mkdir -p "$(dirname "$LOG")" 2>/dev/null || true
            [ "$state" = "prepared" ] && printf '%s override %s=%s %s %s -> %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$OVERRIDE_NAME" "$value" "$ref" "$old_now" "$new" >> "$LOG"
            continue
        fi
        echo "m-flow guard: $ref may not be deleted; a revert commit on top is the forward-only way" >&2
        exit 1
    fi
    old_now=$(git rev-parse --verify "$ref" 2>/dev/null || echo "$zero")
    [ "$old_now" = "$zero" ] && continue
    if git merge-base --is-ancestor "$old_now" "$new" 2>/dev/null; then
        continue
    fi
    if [ -n "$value" ]; then
        [ "$state" = "prepared" ] && mkdir -p "$(dirname "$LOG")" 2>/dev/null || true
        [ "$state" = "prepared" ] && printf '%s override %s=%s %s %s -> %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$OVERRIDE_NAME" "$value" "$ref" "$old_now" "$new" >> "$LOG"
        continue
    fi
    echo "m-flow guard: $ref may only move forward ($old_now -> $new); a revert commit on top is the forward-only way" >&2
    exit 1
done
exit 0
"#
    )
}

/// One shell single-quoted word: any bytes are safe inside it.
fn sh_word(s: &str) -> String {
    format!("'{}'", s.replace('\'', "'\\''"))
}

/// The command words the tool guard refuses before they run: `Some` with the reason when the
/// command aims a forward-breaking git command at the integration branch, `None` when it does
/// not name the branch or names no refused command.
///
/// The command words come from the shell-command splitter and the git subcommand splitter of
/// the hook guards, so `cd elsewhere && git reset …`, `git -C <dir> reset …` and an absolute
/// git path are seen the way git runs them (audit B2). `current_branch` is the checked-out
/// branch of the folder the command runs in; a shell `cd` or `git -C <dir>` replaces it with
/// that folder's.
pub fn guard_rule(
    command: &str,
    integration_branch: &str,
    current_branch: Option<&str>,
) -> Option<String> {
    let mut cwd: Option<String> = None;
    for (program, args) in crate::claim_verify::shell_commands(command) {
        let bin = program.rsplit('/').next().unwrap_or(&program);
        if bin == "cd" {
            cwd = args.first().cloned();
            continue;
        }
        if bin != "git" {
            continue;
        }
        for sub in crate::claim_verify::git_subcommands(&args) {
            // The folder `git -C <dir>` names replaces the caller's checked-out branch, and a
            // shell `cd` replaces it too; an unreadable folder falls back to the integration
            // branch, which errs toward refusing.
            let here = sub
                .global
                .iter()
                .position(|g| g == "-C")
                .and_then(|i| sub.global.get(i + 1))
                .map(|dir| {
                    crate::hook_guards::work_tree_branch(Path::new(dir)).unwrap_or_else(|| {
                        cwd.clone()
                            .unwrap_or_else(|| integration_branch.to_string())
                    })
                })
                .or_else(|| {
                    cwd.as_ref().map(|dir| {
                        crate::hook_guards::work_tree_branch(Path::new(dir)).unwrap_or_else(|| {
                            current_branch.unwrap_or(integration_branch).to_string()
                        })
                    })
                })
                .or_else(|| current_branch.map(str::to_string));
            let warned = match sub.verb.as_str() {
                "reset" => reset_rule(&sub, integration_branch, here.as_deref()),
                "push" => push_rule(&sub, integration_branch),
                "branch" => branch_rule(&sub, integration_branch),
                _ => None,
            };
            if let Some(w) = warned {
                return Some(w);
            }
        }
    }
    None
}

/// `git reset --hard|--keep` moves the checked-out branch, so the guard refuses it whenever
/// the branch the command runs in is the integration branch — the target being a sha,
/// `HEAD~1` or another name makes no difference (audit B2's own incident). Without a resolved
/// branch the command is refused only when it names the integration branch.
fn reset_rule(sub: &GitSub, integration_branch: &str, here: Option<&str>) -> Option<String> {
    let hard = sub.rest.iter().any(|a| a == "--hard" || a == "--keep");
    if !hard {
        return None;
    }
    let touches = match here {
        Some(b) => b == integration_branch,
        None => sub.rest.iter().any(|a| names_branch(a, integration_branch)),
    };
    touches.then(|| {
        format!(
            "m-flow guard: git reset on the integration branch {integration_branch} moves it \
             backwards; add a revert commit on top"
        )
    })
}

/// The branch a push refspec or a branch word names: the `+` and the `refs/heads/` prefix go,
/// and for a refspec the destination — the part after the last `:` — is the branch.
fn names_branch(word: &str, integration_branch: &str) -> bool {
    crate::hook_guards::branch_of_refspec(word) == integration_branch
}

/// `git push` with a force in play and the integration branch among the destination refspecs.
/// A `+` before the refspec is a force of its own: it refuses without a force flag.
fn push_rule(sub: &GitSub, integration_branch: &str) -> Option<String> {
    let forced = sub
        .rest
        .iter()
        .any(|a| crate::hook_guards::push_force_option(a) || a == "-f");
    let hits = crate::hook_guards::push_positionals(&sub.rest)
        .iter()
        .skip(1)
        .any(|spec| names_branch(spec, integration_branch));
    let plus = sub
        .rest
        .iter()
        .any(|a| a.starts_with('+') && names_branch(a, integration_branch));
    ((forced && hits) || plus).then(|| {
        format!(
            "m-flow guard: git push --force to the integration branch {integration_branch} can \
             move it backwards; push a forward commit"
        )
    })
}

/// `git branch -f|-M` moves the branch its first positional names (`-M` may also overwrite the
/// integration branch as the rename target), so the guard refuses when a `-f|-M` positional is
/// the integration branch; `-D` deletes, so any positional naming it is refused.
fn branch_rule(sub: &GitSub, integration_branch: &str) -> Option<String> {
    let letters = crate::hook_guards::short_letters(&sub.rest, &[]);
    let long_force = sub.rest.iter().any(|a| a == "--force");
    let positionals: Vec<&String> = sub.rest.iter().filter(|a| !a.starts_with('-')).collect();
    let named: Vec<bool> = positionals
        .iter()
        .map(|p| names_branch(p, integration_branch))
        .collect();
    let moves = (letters.contains(&'f') || long_force) && named.first().is_some_and(|hit| *hit);
    let renames = letters.contains(&'M') && named.iter().any(|hit| *hit);
    let deletes = letters.contains(&'D') && named.iter().any(|hit| *hit);
    (moves || renames || deletes).then(|| {
        format!(
            "m-flow guard: git branch -f/-D/-M on the integration branch {integration_branch} is \
             refused; move it forward with a commit on top"
        )
    })
}
