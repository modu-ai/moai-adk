func TestBuild_EdgesSortedDeterministically(t *testing.T) {
	root := fixtureProject(t)
	first, err := Build(root)
	if err != nil {
		t.Fatal(err)
	}
	second, err := Build(root)
	if err != nil {
		t.Fatal(err)
	}
	if len(first) == 0 {
		t.Fatal("fixture produced no edges")
	}
	if !sort.SliceIsSorted(first, func(i, j int) bool { return edgeLess(first[i], first[j]) }) {
		t.Errorf("edges not sorted: %v", first)
	}
	if len(first) != len(second) {
		t.Fatalf("non-deterministic edge count: %d vs %d", len(first), len(second))
	}
	for i := range first {
		if first[i] != second[i] {
			t.Errorf("edge %d differs across runs: %+v vs %+v", i, first[i], second[i])
		}
	}
}

func TestWriteJSONL_OneEdgePerLine(t *testing.T) {
	root := fixtureProject(t)
	edges, err := Build(root)
	if err != nil {
		t.Fatal(err)
	}

	out := filepath.Join(root, "edges.jsonl")
	if err := WriteJSONL(out, edges); err != nil {
		t.Fatalf("WriteJSONL: %v", err)
	}

	data, err := os.ReadFile(out)
	if err != nil {
		t.Fatal(err)
	}
	lines := strings.Split(strings.TrimRight(string(data), "\n"), "\n")
	if len(lines) != len(edges) {
		t.Fatalf("want %d lines, got %d", len(edges), len(lines))
	}
	for i, ln := range lines {
		var e Edge
		if err := json.Unmarshal([]byte(ln), &e); err != nil {
			t.Fatalf("line %d is not valid JSON: %v: %q", i, err, ln)
		}
		if e.Kind == "" || e.Source == "" || e.Target == "" {
			t.Fatalf("line %d missing required fields: %q", i, ln)
		}
	}

	// Byte-stable rewrite.
	if err := WriteJSONL(out, edges); err != nil {
		t.Fatal(err)
	}
	data2, _ := os.ReadFile(out)
	if string(data) != string(data2) {
		t.Error("WriteJSONL not byte-stable across runs")
	}
}

// edgeLess is the canonical edge ordering (kind, source, target, line).
func edgeLess(a, b Edge) bool {
	if a.Kind != b.Kind {
		return a.Kind < b.Kind
	}
	if a.Source != b.Source {
		return a.Source < b.Source
	}
	if a.Target != b.Target {
		return a.Target < b.Target
	}
	return a.Line < b.Line
}
