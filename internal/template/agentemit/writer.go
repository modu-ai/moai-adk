// writer.go — deterministic TOML rendering with fail-closed validators.
//
// The emitted grammar is deliberately tiny: full-line comments, bare keys,
// single-line basic strings for identifier-like values, multi-line literal
// strings (triple-apostrophe delimited) for the verbatim description and
// body, and one array of basic strings. Determinism rules (R-006): fixed
// key order, no timestamps, no absolute paths, no environment-derived values.
package agentemit

import (
	"fmt"
	"sort"
	"strings"
)

// tomlHeader is the fixed regeneration notice emitted above every artifact.
const tomlHeader = "# Generated by the MoAI agent dual-publication emitter; regenerate, do not edit."

// basicSafeClass is the byte set allowed in single-line basic-string values
// (identifier-like: no quotes, backslashes, or control characters).
func basicStringSafe(v string) bool {
	if v == "" {
		return false
	}
	for _, r := range v {
		switch {
		case r >= 'a' && r <= 'z',
			r >= 'A' && r <= 'Z',
			r >= '0' && r <= '9',
			r == '-', r == '_', r == '.':
		default:
			return false
		}
	}
	return true
}

// literalString validates s for representability inside a TOML multi-line
// literal string and returns the wrapped opening delimiter, newline, value,
// closing delimiter.
//
// Fail-closed (R-008): a value containing the three-apostrophe delimiter, a
// carriage return, or a control character other than tab/newline is
// unrepresentable without escape processing — literal strings exist
// precisely so the body needs none — and emission must fail rather than
// emit a structurally broken or silently-altered file.
func literalString(filename, field, s string) (string, error) {
	if strings.Contains(s, "'''") {
		return "", fmt.Errorf("%s: %s contains the TOML multi-line literal delimiter ''' — unrepresentable body, emission refused", filename, field)
	}
	if strings.ContainsRune(s, '\r') {
		return "", fmt.Errorf("%s: %s contains a carriage return (CR) — unrepresentable in a verbatim literal string, emission refused", filename, field)
	}
	for i := 0; i < len(s); i++ {
		c := s[i]
		if c < 0x20 && c != '\t' && c != '\n' {
			return "", fmt.Errorf("%s: %s contains control byte 0x%02x — unrepresentable in a literal string, emission refused", filename, field, c)
		}
	}
	return "'''\n" + s + "'''", nil
}

// classifyToken maps a Claude tool token to its semantic class through the
// manifest. Exact matches win; keys ending in "__" are prefix rules (e.g.
// "mcp__moai__" covers every mcp__moai__<tool> token). Unknown tokens return
// ok=false — the caller fails closed (AC-005).
func classifyToken(man Manifest, token string) (class string, ok bool) {
	if c, hit := man.ToolClasses[token]; hit {
		return c, true
	}
	// Deterministic prefix-rule evaluation: sorted keys, first hit wins.
	prefixes := make([]string, 0, len(man.ToolClasses))
	for k := range man.ToolClasses {
		if strings.HasSuffix(k, "__") {
			prefixes = append(prefixes, k)
		}
	}
	sort.Strings(prefixes)
	for _, p := range prefixes {
		if strings.HasPrefix(token, p) {
			return man.ToolClasses[p], true
		}
	}
	return "", false
}

// renderTOML renders one agent's Codex TOML. Key order is fixed:
// name, description, developer_instructions, mcp_servers (conditional),
// model_reasoning_effort (conditional), sandbox_mode (conditional).
// Every validation error names the source .md file and the offending value.
// The second return value is the emitted sandbox_mode ("" when not emitted).
//
// A role with a Codex-only addendum in the manifest gets that text appended
// after its verbatim body; the neutral .md is never touched.
func renderTOML(doc AgentDoc, man Manifest, hasMCP bool) ([]byte, string, error) {
	if !basicStringSafe(doc.Name) {
		return nil, "", fmt.Errorf("%s: agent name %q is not representable as a TOML basic string", doc.File, doc.Name)
	}
	desc, err := literalString(doc.File, "description", doc.Description)
	if err != nil {
		return nil, "", err
	}
	addendum, hasAddendum := man.CodexRoleAddenda[doc.Name]
	instructions := string(doc.Body)
	if hasAddendum {
		instructions += "\n" + strings.TrimRight(addendum, "\n") + "\n"
	}
	body, err := literalString(doc.File, "developer_instructions (body)", instructions)
	if err != nil {
		return nil, "", err
	}

	var b strings.Builder
	b.WriteString(tomlHeader + "\n")
	fmt.Fprintf(&b, "# Neutral source: .claude/agents/moai/%s (body carried verbatim).\n", doc.File)
	if hasAddendum {
		b.WriteString("# Codex-only addendum appended after the verbatim body (mapping manifest).\n")
	}
	fmt.Fprintf(&b, "name = %q\n", doc.Name)
	b.WriteString("description = " + desc + "\n")
	b.WriteString("developer_instructions = " + body + "\n")

	if fc, ok := man.Fields["model_reasoning_effort"]; ok && fc.Emit {
		mapped, found := fc.Map[doc.Effort]
		if !found {
			return nil, "", fmt.Errorf("%s: effort value %q is not in the manifest's measured model_reasoning_effort enumeration — refusing to guess (silent-ignore hazard)", doc.File, doc.Effort)
		}
		if !basicStringSafe(mapped) {
			return nil, "", fmt.Errorf("%s: mapped effort %q is not representable as a TOML basic string", doc.File, mapped)
		}
		fmt.Fprintf(&b, "model_reasoning_effort = %q\n", mapped)
	}

	emittedSandbox := ""
	if fc, ok := man.Fields["sandbox_mode"]; ok && fc.Emit {
		mode := fc.Value
		if override, ok := fc.RoleValues[doc.Name]; ok {
			mode = override
		}
		measured := false
		for _, value := range fc.AcceptedValues {
			if mode == value {
				measured = true
				break
			}
		}
		if !measured {
			return nil, "", fmt.Errorf("%s: role %q sandbox_mode %q is outside the measured value set", doc.File, doc.Name, mode)
		}
		if !basicStringSafe(mode) {
			return nil, "", fmt.Errorf("manifest sandbox_mode value %q is not representable as a TOML basic string", mode)
		}
		// A read-only role carrying a write tool is refused, unless the
		// manifest gives it a Codex-only addendum: that addendum moves the
		// write to the parent (the role returns its text instead).
		if mode == "read-only" && !hasAddendum {
			for _, tool := range doc.Tools {
				if tool == "Write" || tool == "Edit" {
					return nil, "", fmt.Errorf("%s: read-only role %q carries write tool %q", doc.File, doc.Name, tool)
				}
			}
		}
		fmt.Fprintf(&b, "sandbox_mode = %q\n", mode)
		emittedSandbox = mode
	}

	// MCP server grant LAST, as a TOML table: sections must follow all root
	// scalar keys. Map shape is the run-phase-measured form — codex-cli
	// 0.147.0 rejects the array form ("invalid type: sequence, expected a
	// map") by dropping the whole agent file.
	if hasMCP {
		grant := man.MCPServerGrant
		if grant == nil {
			return nil, "", fmt.Errorf("%s: agent carries moai-mcp tools but manifest has no mcp_server_grant", doc.File)
		}
		if !basicStringSafe(grant.Server) || !basicStringSafe(grant.Command) {
			return nil, "", fmt.Errorf("%s: mcp_server_grant names are not representable as TOML basic strings", doc.File)
		}
		fmt.Fprintf(&b, "[mcp_servers.%s]\ncommand = %q\nargs = [", grant.Server, grant.Command)
		for i, a := range grant.Args {
			if i > 0 {
				b.WriteString(", ")
			}
			if !basicStringSafe(a) {
				return nil, "", fmt.Errorf("%s: mcp_server_grant arg %q is not representable as a TOML basic string", doc.File, a)
			}
			fmt.Fprintf(&b, "%q", a)
		}
		b.WriteString("]\n")
	}

	return []byte(b.String()), emittedSandbox, nil
}
